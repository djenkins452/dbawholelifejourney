"""
DBE — Daily Briefing Model.

Stores one briefing per user per day. Contains snapshots of the intelligence
state at briefing generation time for auditability.
"""

from django.conf import settings
from django.db import models


class DailyBriefing(models.Model):
    """
    A daily intelligence summary for a user.

    Generated by aggregating SAE state, PIE insights, PRIE predictions,
    and PGE guidance. One briefing per user per day (enforced by unique
    constraint).
    """

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="daily_briefings",
    )
    briefing_date = models.DateField(
        help_text="The date this briefing covers.",
    )
    summary = models.TextField(
        help_text="Human-readable briefing summary text.",
    )
    state_snapshot = models.JSONField(
        default=dict,
        blank=True,
        help_text="SAE state at briefing time.",
    )
    guidance_snapshot = models.JSONField(
        default=dict,
        blank=True,
        help_text="PGE guidance items included in briefing.",
    )
    insight_snapshot = models.JSONField(
        default=dict,
        blank=True,
        help_text="PIE insights included in briefing.",
    )
    prediction_snapshot = models.JSONField(
        default=dict,
        blank=True,
        help_text="PRIE predictions included in briefing.",
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        app_label = "core"
        db_table = "core_daily_briefing"
        constraints = [
            models.UniqueConstraint(
                fields=["user", "briefing_date"],
                name="unique_user_briefing_date",
            ),
        ]
        ordering = ["-briefing_date"]
        verbose_name = "Daily Briefing"
        verbose_name_plural = "Daily Briefings"

    def __str__(self):
        return f"Briefing for {self.user_id} on {self.briefing_date}"
