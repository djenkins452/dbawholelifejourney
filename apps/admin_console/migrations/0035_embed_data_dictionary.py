def _pick_icon(title):
    title_lower = title.lower()
    for keyword, icon in SECTION_ICONS.items():
        if keyword in title_lower:
            return icon
    return '📄'


def _clean_section_title(raw):
    return re.sub(r'^\d+\.\s*', '', raw).strip()


def populate_data_dictionary(apps, schema_editor):
    """Create Data Dictionary sections and articles from embedded markdown."""
    AdminGuideSection = apps.get_model('admin_console', 'AdminGuideSection')
    AdminGuideArticle = apps.get_model('admin_console', 'AdminGuideArticle')

    # Decode the embedded content
    compressed = base64.b64decode(_DD_CONTENT_B64)
    content = gzip.decompress(compressed).decode('utf-8')

    # Split by ## headers
    pattern = r'^## (.+)$'
    parts = re.split(pattern, content, flags=re.MULTILINE)

    sections = []
    i = 1
    while i < len(parts):
        raw_title = parts[i].strip()
        body = parts[i + 1].strip() if i + 1 < len(parts) else ''
        i += 2
        if raw_title.lower() == 'table of contents':
            continue
        title = _clean_section_title(raw_title)
        sections.append((title, body))

    print(f'  [DATA DICT] Parsed {len(sections)} sections from embedded content')

    created_sections = 0
    created_articles = 0

    for order, (title, body) in enumerate(sections):
        section_key = slugify(title)[:100]
        icon = _pick_icon(title)

        section, sec_created = AdminGuideSection.objects.update_or_create(
            guide_type='data_dictionary',
            section_key=section_key,
            defaults={
                'title': title,
                'icon': icon,
                'description': '',
                'order': order,
                'is_active': True,
            },
        )
        if sec_created:
            created_sections += 1

        # Split section body into articles by ### headers
        art_pattern = r'^### (.+)$'
        art_parts = re.split(art_pattern, body, flags=re.MULTILINE)

        articles = []
        preamble = art_parts[0].strip()
        if preamble and len(art_parts) > 1:
            articles.append((f"{title} Overview", preamble))
        elif len(art_parts) <= 1:
            articles.append((title, body))

        j = 1
        while j < len(art_parts):
            art_title = art_parts[j].strip()
            art_body = art_parts[j + 1].strip() if j + 1 < len(art_parts) else ''
            j += 2
            articles.append((art_title, art_body))

        for art_order, (art_title, art_content) in enumerate(articles):
            art_slug = slugify(art_title)[:200]
            _, art_created = AdminGuideArticle.objects.update_or_create(
                section=section,
                slug=art_slug,
                defaults={
                    'title': art_title,
                    'content': art_content,
                    'order': art_order,
                    'is_editable': False,
                    'is_active': True,
                },
            )
            if art_created:
                created_articles += 1

    print(f'  [DATA DICT] Created {created_sections} sections, {created_articles} articles')


